SELECT        SYSTEM_USERS.SYSTEM_USERS_ID, SYSTEM_USERS.F_NAME, POSTS.DESCRIPTION, BASIC_PAY_SCALES.DESCRIPTION AS Expr1, BRANCHES.DESCRIPTION AS Expr2, EMP_POSTINGS.DATE_FROM, 
                         EMP_POSTINGS.DATE_TO, EMP_POSTINGS.REMARKS, EMP_POSTINGS.ADDITIONAL_BRANCHES, BRANCHES.BRANCHES_ID, POSTS.POSTS_ID
FROM            SYSTEM_USERS INNER JOIN
                         EMP_POSTINGS ON SYSTEM_USERS.SYSTEM_USERS_ID = EMP_POSTINGS.SYSTEM_USERS_ID INNER JOIN
                         POSTS ON EMP_POSTINGS.POST_ID = POSTS.POSTS_ID INNER JOIN
                         BASIC_PAY_SCALES ON EMP_POSTINGS.BPS_ID = BASIC_PAY_SCALES.BASIC_PAY_SCALES_ID INNER JOIN
                         BRANCHES ON EMP_POSTINGS.BRANCH_ID = BRANCHES.BRANCHES_ID
						 where EMP_POSTINGS.BRANCH_ID=125 and EMP_POSTINGS.POST_ID=3
						 order by BRANCHES.DESCRIPTION

SELECT        SYSTEM_USERS.SYSTEM_USERS_ID, SYSTEM_USERS.F_NAME, POSTS.DESCRIPTION, EMP_OTHER_CHARGES.FROM_DATE, EMP_OTHER_CHARGES.TO_DATE, EMP_OTHER_CHARGES.REMARKS, 
                         BASIC_PAY_SCALES.DESCRIPTION AS Expr1, BRANCHES.DESCRIPTION AS Expr2
FROM            SYSTEM_USERS INNER JOIN
                         EMP_OTHER_CHARGES ON SYSTEM_USERS.SYSTEM_USERS_ID = EMP_OTHER_CHARGES.SYSTEM_USERS_ID INNER JOIN
                         POSTS ON EMP_OTHER_CHARGES.POSTS_ID = POSTS.POSTS_ID INNER JOIN
                         BASIC_PAY_SCALES ON EMP_OTHER_CHARGES.BPS_ID = BASIC_PAY_SCALES.BASIC_PAY_SCALES_ID INNER JOIN
                         BRANCHES ON EMP_OTHER_CHARGES.BRANCH_ID = BRANCHES.BRANCHES_ID
						 where EMP_OTHER_CHARGES.POSTS_ID=3 and EMP_OTHER_CHARGES.BRANCH_ID=13



